import { test, expect } from '@playwright/test'
import { openForecast,server } from './helpers/forecast'
test.use({storageState:{cookies:[],origins:[]},serviceWorkers:'block',
  ...(process.env.CHAT_UI_BROWSER_EXECUTABLE ? {launchOptions:{executablePath:process.env.CHAT_UI_BROWSER_EXECUTABLE}} : {})})
for(const width of [1280,390]) test(`encrypted provider key lifecycle at ${width}px`,async({page,request})=>{
  await request.post(server+'/reset'); await request.post(server+'/reset-keys')
  await page.setViewportSize({width,height:1000})
  const {browserErrors}=await openForecast(page,request)
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  const panel=page.getByRole('region',{name:'AI providers'})
  const gemini=panel.getByRole('group',{name:'Gemini',exact:true})
  await expect(gemini).toContainText('No key saved')
  await expect(panel).toContainText('Additional financial-analysis mode is not enabled')
  const input=gemini.getByLabel('Gemini API key',{exact:true})
  await expect(input).toHaveAttribute('type','password')
  await input.fill('synthetic-browser-key-1234')
  await gemini.getByRole('button',{name:'Save Gemini key'}).click()
  await expect(input).toHaveValue('')
  await expect(gemini).toContainText('Saved key ending in 1234')
  expect((await (await request.get(server+'/key-storage-audit')).json())).toEqual({rows:1,encrypted:true})
  const meta=await request.get(server+'/profile/ai-providers')
  expect(await meta.text()).not.toContain('synthetic-browser-key')
  expect(await meta.text()).not.toContain('ciphertext')
  const other=await request.get(server+'/profile/ai-providers',{headers:{'X-Test-User':'00000000-0000-4000-8000-000000000002'}})
  expect((await other.json()).providers[0].configured).toBe(false)
  await gemini.getByRole('button',{name:'Test Gemini key'}).click()
  await expect(gemini).toContainText('Authentication succeeded')
  await page.reload(); await page.getByRole('button',{name:'Settings',exact:true}).click()
  await expect(gemini).toContainText('Saved key ending in 1234')
  await input.fill('synthetic-browser-key-invalid')
  await gemini.getByRole('button',{name:'Replace Gemini key'}).click()
  await expect(gemini).toContainText('Saved key ending in alid')
  await gemini.getByRole('button',{name:'Test Gemini key'}).click()
  await expect(gemini.getByRole('alert')).toContainText('Authentication check failed')
  await gemini.getByRole('button',{name:'Remove Gemini key'}).click()
  await gemini.getByRole('button',{name:'Confirm remove Gemini key'}).click()
  await expect(gemini).toContainText('No key saved')
  const openrouter=panel.getByRole('group',{name:'OpenRouter',exact:true})
  await openrouter.getByLabel('OpenRouter API key').fill('synthetic-openrouter-5678')
  await openrouter.getByRole('button',{name:'Save OpenRouter key'}).click()
  await expect(openrouter).toContainText('Saved key ending in 5678')
  await openrouter.getByRole('button',{name:'Test OpenRouter key'}).click()
  await expect(openrouter).toContainText('Authentication succeeded')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  await panel.screenshot({path:`test-results/provider-keys-${width}.png`})
  expect(browserErrors).toEqual([])
})
test('missing encryption fails closed and failed saves can be retried',async({page,request})=>{
  await request.post(server+'/reset');await request.post(server+'/reset-keys?disabled=true')
  await openForecast(page,request)
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  const panel=page.getByRole('region',{name:'AI providers'})
  await expect(panel.getByRole('alert')).toContainText('AI key storage is unavailable')
  await expect(panel.getByLabel('Gemini API key')).toBeDisabled()
  await request.post(server+'/reset-keys')
  await page.reload();await page.getByRole('button',{name:'Settings',exact:true}).click()
  await panel.getByLabel('Gemini API key').fill('synthetic-key-for-retry')
  await page.route('**/profile/ai-providers/gemini',async route=>route.fulfill({status:503,json:{detail:'unavailable'}}))
  await panel.getByRole('button',{name:'Save Gemini key'}).click()
  await expect(panel.getByRole('alert')).toContainText('Could not complete this action')
  await page.unroute('**/profile/ai-providers/gemini')
  await panel.getByRole('button',{name:'Save Gemini key'}).click()
  await expect(panel).toContainText('Saved key ending in etry')
})
test('advisor and import errors link to provider settings', async ({page,request}) => {
  await request.post(server+'/reset'); await request.post(server+'/reset-keys')
  await openForecast(page,request)
  await page.getByRole('button',{name:'Open advisor',exact:true}).click()
  await page.getByRole('button',{name:'AI provider settings',exact:true}).click()
  await expect(page.getByRole('region',{name:'AI providers'})).toBeVisible()
  await page.getByRole('button',{name:'+ Import statements',exact:true}).click()
  await page.getByLabel('This file contains multiple accounts').check()
  await page.locator('input[type=file]').setInputFiles({name:'synthetic.txt',mimeType:'text/plain',buffer:Buffer.from('Synthetic checking statement')})
  await page.route('**/import/statements/detect', route => route.fulfill({status:409,json:{detail:'Save a Gemini key in Settings.'}}))
  await page.getByTestId('unified-preview-btn').click()
  await page.getByRole('button',{name:'AI provider settings',exact:true}).click()
  await expect(page.getByRole('region',{name:'AI providers'})).toBeVisible()
  await expect(page.getByTestId('unified-preview-btn')).toHaveCount(0)
})
